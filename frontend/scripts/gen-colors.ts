// Generates app/colors.generated.css from theme/colors.json, the single source
// of truth for every color in the app. Tailwind's CSS pipeline cannot import
// JSON directly, so this script emits the equivalent CSS variables.
// Run `bun scripts/gen-colors.ts` (also runs automatically before dev/build).
import { readFileSync, writeFileSync } from "node:fs"
import { join, resolve } from "node:path"

const root = resolve(import.meta.dirname, "..")
const inFile = join(root, "theme/colors.json")
const outFile = join(root, "app/colors.generated.css")

type Palette = Record<string, string>
type Colors = { brand: Palette; light: Palette; dark: Palette }

const colors = JSON.parse(readFileSync(inFile, "utf8")) as Colors

for (const group of ["brand", "light", "dark"] as const) {
  const entries = colors[group]
  if (!entries || typeof entries !== "object") {
    throw new Error(`theme/colors.json: missing "${group}" group`)
  }
  for (const [name, value] of Object.entries(entries)) {
    if (typeof value !== "string" || value.trim() === "") {
      throw new Error(`theme/colors.json: ${group}.${name} must be a non-empty string`)
    }
  }
}

const decl = (p: Palette, fn: (k: string) => string) =>
  Object.entries(p).map(([k, v]) => `  ${fn(k)}: ${v};`)

const themeNames = Object.keys(colors.light)

const out = [
  "/* AUTO-GENERATED by scripts/gen-colors.ts from theme/colors.json. Do not edit. */",
  "",
  "@theme inline {",
  ...themeNames.map((k) => `  --color-${k}: var(--${k});`),
  ...Object.keys(colors.brand).map((k) => `  --color-${k}: var(--${k});`),
  "}",
  "",
  ":root {",
  ...decl(colors.brand, (k) => `--${k}`),
  ...decl(colors.light, (k) => `--${k}`),
  "}",
  "",
  ".dark {",
  ...decl(colors.dark, (k) => `--${k}`),
  "}",
  "",
].join("\n")

writeFileSync(outFile, out)
