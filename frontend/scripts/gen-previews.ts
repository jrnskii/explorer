// Generates app/preview/registry.generated.ts from every `*.preview.tsx`
// file under components/. Run with `--watch` to regenerate on changes
// (Next's HMR then refreshes the /preview page automatically).
import { existsSync, readFileSync, readdirSync, watch, writeFileSync } from "node:fs"
import { join, relative, resolve } from "node:path"

const root = resolve(import.meta.dirname, "..")
const componentsDir = join(root, "components")
const outFile = join(root, "app/preview/registry.generated.ts")

function findPreviews(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = join(dir, e.name)
    if (e.isDirectory()) return findPreviews(p)
    return e.name.endsWith(".preview.tsx") ? [p] : []
  })
}

function generate() {
  const files = existsSync(componentsDir) ? findPreviews(componentsDir).sort() : []
  const entries = files.map((f, i) => {
    const rel = relative(componentsDir, f).replace(/\.preview\.tsx$/, "")
    return { name: rel, ident: `Preview${i}`, spec: `@/components/${rel}.preview` }
  })

  const out = [
    "// AUTO-GENERATED by scripts/gen-previews.ts. Do not edit.",
    ...entries.map((e) => `import ${e.ident} from "${e.spec}"`),
    "",
    "export const previews: { name: string; Component: React.ComponentType }[] = [",
    ...entries.map((e) => `  { name: ${JSON.stringify(e.name)}, Component: ${e.ident} },`),
    "]",
    "",
  ].join("\n")

  const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : ""
  if (current !== out) {
    writeFileSync(outFile, out)
    console.log(`[previews] ${entries.length} component preview(s): ${entries.map((e) => e.name).join(", ") || "-"}`)
  }
}

generate()

if (process.argv.includes("--watch")) {
  let timer: ReturnType<typeof setTimeout> | undefined
  watch(componentsDir, { recursive: true }, (_event, filename) => {
    if (!filename?.endsWith(".preview.tsx")) return
    clearTimeout(timer)
    timer = setTimeout(generate, 50)
  })
  console.log("[previews] watching components/ for *.preview.tsx")
}
