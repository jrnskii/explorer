// One-off generator for lib/europe-geo.ts.
// Usage: node scripts/gen-europe-geo.mjs /path/to/ne_50m_admin_0_countries.geojson
// Source data: Natural Earth (public domain).
import { readFileSync, writeFileSync } from "node:fs"

const BBOX = { minLon: -14, maxLon: 40, minLat: 32, maxLat: 73 }
const TOLERANCE = 0.05 // degrees, Douglas-Peucker

const src = JSON.parse(readFileSync(process.argv[2], "utf8"))

function perpDist(p, a, b) {
  const dx = b[0] - a[0]
  const dy = b[1] - a[1]
  if (dx === 0 && dy === 0) return Math.hypot(p[0] - a[0], p[1] - a[1])
  const t = ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / (dx * dx + dy * dy)
  const c = Math.max(0, Math.min(1, t))
  return Math.hypot(p[0] - (a[0] + c * dx), p[1] - (a[1] + c * dy))
}

function simplify(pts, tol) {
  if (pts.length < 3) return pts
  let max = 0
  let idx = 0
  for (let i = 1; i < pts.length - 1; i++) {
    const d = perpDist(pts[i], pts[0], pts[pts.length - 1])
    if (d > max) {
      max = d
      idx = i
    }
  }
  if (max <= tol) return [pts[0], pts[pts.length - 1]]
  return [
    ...simplify(pts.slice(0, idx + 1), tol).slice(0, -1),
    ...simplify(pts.slice(idx), tol),
  ]
}

const inBox = ([lon, lat]) =>
  lon >= BBOX.minLon &&
  lon <= BBOX.maxLon &&
  lat >= BBOX.minLat &&
  lat <= BBOX.maxLat

const rings = []
for (const f of src.features) {
  if (f.properties.ADM0_A3 === "ATA" || f.properties.ADM0_A3 === "GRL") continue
  const geom = f.geometry
  const polys = geom.type === "Polygon" ? [geom.coordinates] : geom.coordinates
  for (const poly of polys) {
    const outer = poly[0] // skip holes (lakes/enclaves) for a minimal look
    if (!outer.some(inBox)) continue
    // Clamp far-away vertices (e.g. eastern Russia) so shapes stay bounded.
    const clamped = outer.map(([lon, lat]) => [
      Math.max(-30, Math.min(70, lon)),
      Math.max(20, Math.min(85, lat)),
    ])
    const s = simplify(clamped, TOLERANCE)
    if (s.length < 4) continue
    rings.push(s.map(([lon, lat]) => [+lon.toFixed(2), +lat.toFixed(2)]))
  }
}

const out = `// Generated by scripts/gen-europe-geo.mjs from Natural Earth 1:50m (public domain).
// Do not edit manually. Each ring is a closed list of [lon, lat] pairs (WGS84).

export const EUROPE_RINGS: ReadonlyArray<ReadonlyArray<readonly [number, number]>> = ${JSON.stringify(rings)}
`
writeFileSync(new URL("../lib/europe-geo.ts", import.meta.url), out)
console.log(`rings: ${rings.length}, bytes: ${out.length}`)
